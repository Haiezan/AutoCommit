namespace AutoCommit.Core;

public static class DefaultRules
{
    public const string Text = @"# 提交规范

## 基本原则
- 使用中文描述，保留必要的代码标识符和专有名词。
- 只总结本次暂存差异，不描述未暂存修改或推测的工作。
- 输出可直接用于 Git 的纯文本，不使用代码围栏或额外解释。

## 标题
- 格式：type(scope): 摘要；无法可靠判断 scope 时使用 type: 摘要。
- type 只能使用 feat、fix、docs、refactor、test、chore。
- feat 表示新增功能；fix 表示缺陷修复；docs 表示文档；refactor 表示重构；test 表示测试；chore 表示构建、依赖或维护。
- 选择最能代表主要变更的类型。scope 使用实际模块名，不编造模块。
- 标题不超过 72 个字符，使用具体动词，不使用“更新代码”等空泛表述，不以句号结尾。

## 正文
- 标题与正文之间空一行。正文使用以“- ”开头的列表。
- 按模块或用户可见行为归纳主要变化，避免机械列出所有文件。
- 修改原因仅在差异或明确上下文中有证据时说明。
- 涉及配置、依赖、接口或数据结构变化时说明实际影响。
- 简单修改可省略正文，避免重复标题。

## 真实性与兼容性
- 不编造工单编号、测试结果、性能收益或安全结论。
- 新增测试只能表述为“新增测试覆盖”，不能声称测试已通过。
- 仅在有明确证据时增加 BREAKING CHANGE: 段落，说明不兼容影响及已知迁移方式。
- 二进制文件无法分析内容时只描述文件变动，不推断内部修改。
- 不在提交说明中复述密钥、口令等敏感内容。

## 示例
fix(auth): 修复令牌过期后的重复刷新

- 合并并发刷新请求，复用进行中的刷新任务
- 新增令牌过期场景的测试用例
";
}
